def test_mask_keeps_recipe_ids_and_times() -> None:
    raw = "Dispatch R02 and tool R01. ECN0000001. 2023-01-01T07:00 and 2023-01-05T16:00. pressure=350 mTorr flow=12 sccm temperature=80 °C"
    masked = mask_recipe_text(raw)
    assert "R02" in masked
    assert "R01" in masked
    assert "ECN0000001" in masked
    assert "2023-01-01T07:00" in masked
    assert "2023-01-05T16:00" in masked
    assert "350" not in masked
    assert "mTorr" not in masked
    assert "[set-point]" in masked


def test_budget_skips_a_missing_user_and_blocks_a_signed_in_user(monkeypatch) -> None:
    monkeypatch.setenv("FF_LLM_DAILY_TOKENS", "1")
    reset_budget()
    set_actor("")
    assert budget_allows("x" * 100)
    set_actor("engineer.az")
    assert budget_allows("short")
    charge("x" * 80)
    called = {"n": 0}

    def boom(*_args, **_kwargs):
        called["n"] += 1
        return {"ok": False, "error_class": "azure_call_failed"}

    monkeypatch.setattr("apps.app_a.intelligence.generate.complete_azure", boom)
    monkeypatch.setenv("MODEL_MODE", "azure")
    result = generate("Which recipe_release limit applied to EMEA on 2023-07-01?")
    assert result["error_class"] == "llm_budget_exceeded"
    assert called["n"] == 0
    monkeypatch.setenv("MODEL_MODE", "replay")
    set_actor("")
    reset_budget()


def test_replay_file_is_kept_when_it_already_exists(tmp_path) -> None:
    path = tmp_path / "frozen.txt"
    path.write_text("keep-me", encoding="utf-8")
    assert save_replay(path, "new text") == "kept_frozen"
    assert path.read_text(encoding="utf-8") == "keep-me"
    fresh = tmp_path / "new.txt"
    assert save_replay(fresh, "first") == "saved"
    assert fresh.read_text(encoding="utf-8") == "first"


def test_ask_question_bytes_match_and_hints_are_in_the_lake() -> None:
    record = {
        "measured_yield": 90.4,
        "engineering_hold": 1,
        "tool_id": "T0000007",
        "dispatch_recipe": "R02",
        "equipment_recipe": "R01",
    }
    question, _facts = build_question("lot", record, "explain")
    assert "engineer.az" not in question
    assert "FAB-01" not in question
    assert "FAB-02" not in question
    left = bytes_a(
        prompt_id="P-EXPLAIN-CONFLICT",
        semver="1",
        system="cite or abstain",
        retrieved_item_ids=hint_ids("lot"),
        question=question,
        case_id=None,
    )
    right = bytes_b(
        prompt_id="P-EXPLAIN-CONFLICT",
        semver="1",
        system="cite or abstain",
        retrieved_item_ids=hint_ids("lot"),
        question=question,
        case_id=None,
    )
    assert left == right
    conn = sqlite3.connect(f"file:{LAKE_DB.resolve().as_posix()}?mode=ro", uri=True)
    found = {row[0] for row in conn.execute("SELECT id FROM items")}
    conn.close()
    needed = []
    for values in HINTS.values():
        needed.extend(values)
    missing = [item_id for item_id in needed if item_id not in found]
    assert missing == []


def test_both_apps_ask_the_same_question(api_headers) -> None:
    from apps.app_a.server import app as app_a

    payload = {"subject": "lot", "id": "L00000000", "mode": "explain"}
    left = TestClient(app_a).post("/api/ask", headers=api_headers, json=payload)
    right = TestClient(app_b).post("/api/ask", headers=api_headers, json=payload)
    assert left.status_code == 200
    assert right.status_code == 200
    assert left.json()["question"] == right.json()["question"]
    assert left.json()["source_badge"]["label"]
    label = right.json()["source_badge"]["label"]
    assert "Generated by" not in label
    assert "no model" in label or "no claim made" in label
    assert "rule_trace" in right.json()
