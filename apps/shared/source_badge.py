"""Answer source label. The model name arrives as text. This module does not load a model client."""
from __future__ import annotations

from typing import Any


def source_badge(
    *,
    app_code: str,
    answer_source: str,
    model_name: str = "",
    error_class: str | None = None,
    fallback: bool = False,
    block: bool = False,
) -> dict[str, str]:
    model = model_name or "saved model"
    if block:
        label = _label(app_code, answer_source, model, error_class=None, fallback=fallback)
    elif error_class in {"azure_call_failed", "replay_miss"} or (answer_source == "replay_file" and error_class):
        if app_code == "b" or error_class == "replay_miss":
            label = "No saved answer for this question (offline) · no claim made"
        else:
            label = "Azure OpenAI did not answer · no claim made"
    else:
        label = _label(app_code, answer_source, model, error_class=error_class, fallback=fallback)
    kind = "block" if block else (answer_source or "none")
    tone = "neutral"
    return {"kind": kind, "tone": tone, "model": model_name, "label": label}


def _label(app_code: str, answer_source: str, model: str, *, error_class: str | None, fallback: bool) -> str:
    if app_code == "a" and answer_source == "azure" and not error_class:
        suffix = " (fallback)" if fallback else ""
        return f"Generated by Azure OpenAI · {model}{suffix}"
    if app_code == "a" and answer_source == "replay_file":
        return f"Saved {model} answer (offline replay) · no model call"
    if app_code == "b" and answer_source == "replay_file":
        return "Replayed saved answer · no model call"
    if answer_source == "lake_statement":
        return "Reviewed lake answer · no model"
    return "No saved answer for this question (offline) · no claim made"


def apply_badge(payload: dict[str, Any], *, app_code: str, model_name: str) -> dict[str, Any]:
    badge = source_badge(
        app_code=app_code,
        answer_source=str(payload.get("answer_source") or ""),
        model_name=model_name,
        error_class=payload.get("error_class"),
        fallback=bool(payload.get("fallback")),
        block=bool(payload.get("block")),
    )
    payload["model"] = model_name
    payload["source_badge"] = badge
    return payload
